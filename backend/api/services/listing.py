"""Общие кирпичи списочных разделов.

Товары, материалы, контрагенты и поставки устроены одинаково: отобрать,
посчитать показатели, собрать сводку с топами, отсортировать, отдать страницу.
Одинаковой была и реализация — своя в каждом разделе. Из-за этого одна и та же
ошибка (подзапрос-множество внутри агрегата) жила сразу в четырёх местах, и
править её пришлось четырежды.

Здесь лежит то, что у всех четырёх совпадает дословно. Сам расчёт показателей
не совпадает и сюда не попал: у материалов он идёт по двум разным связям и
склеивается в Python, у остальных — одной аннотацией. Загонять оба случая под
общий интерфейс значило бы прятать разницу, которая как раз важна.
"""

from django.core.paginator import Paginator
from django.db.models import Q


def search_q(search, *fields):
    """Условие поиска по нескольким словам сразу по нескольким полям.

    Слова соединяются «и», поля — «или»: запрос «банка 600» найдёт позицию,
    где есть оба слова, пусть даже одно в названии, а другое в артикуле.
    Порядок слов значения не имеет, и это важнее точности совпадения —
    наименования в МойСкладе записаны кто во что горазд.

    Пустой поиск даёт пустое условие: `filter(Q())` ничего не сужает, так что
    вызывающему не нужно проверять строку отдельно.
    """
    condition = Q()
    for word in search.split():
        word_condition = Q()
        for field in fields:
            word_condition |= Q(**{f'{field}__icontains': word})
        condition &= word_condition
    return condition


def paginate(items, page, page_size):
    """Страница и общее число строк.

    Принимает и список, и QuerySet: у материалов показатели склеиваются
    в Python, у остальных считаются в базе.
    """
    paginator = Paginator(items, page_size)
    return paginator.get_page(page), paginator.count


def top_n(rows, key, build, limit=3):
    """Первые `limit` строк по убыванию `key`, разложенные функцией `build`.

    Считается по уже прочитанной выборке. Прежде каждый топ был отдельным
    запросом с той же агрегацией: три повтора тяжёлого расчёта ради девяти
    строк.
    """
    return [build(row) for row in sorted(rows, key=key, reverse=True)[:limit]]
