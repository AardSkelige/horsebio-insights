"""Файл импорта для админки сайта — запасной путь, когда обмен недоступен.

Обмен CommerceML работает в демо-режиме с лимитом на число загруженных
предложений. Когда лимит выбран, сайт продолжает принимать файлы и отвечать
`success`, но часть полей молча не применяет — поэтому полагаться на него
нельзя, а карточки заводить надо.

Импорт CSV в админке лимитов не имеет: 81 колонка, ключ — артикул, дублей
не создаёт. Мы отдаём подмножество колонок, которым управляем; всё остальное
в карточке остаётся как было.

Описание собирается как врезка про срок годности плюс текст основной карточки —
его читаем прямо со страницы товара, потому что фид отдаёт только анонс. Если описание
прочитать не удалось, колонка остаётся пустой у этой строки: лучше не заполнить, чем
затереть несколько тысяч знаков коротким текстом.

Кодировка cp1251 и разделитель `;` — требование админки, менять нельзя.
Заголовок каждой колонки имеет вид `поле : Человеческое название`.

**Настройка «Операция над товарами, не участвующими в импорте» должна стоять
прочерком** — иначе импорт удалит или скроет все товары, которых нет в файле.
"""

import csv
import io

# Колонка → подпись в шапке файла, ровно как в экспорте админки
COLUMNS = [
    ("article", "Артикул"),
    ("name", "Название"),
    ("folder", "Категория"),
    ("hidden", "Скрыто"),
    ("price", "Цена"),
    ("price_old", "Старая цена"),
    ("amount", "Количество"),
    ("discounted", "Не применять скидки к товару"),
    ("note", "Анонс товара"),
    ("body", "Описание"),
    ("image", "Иллюстрация"),
    ("sef_url", "ЧПУ"),
    ("seo_noindex", "Индексация"),
    ("seo_h1", "Заголовок (H1)"),
    ("seo_title", "Title"),
    ("seo_description", "Description"),
    ("seo_keywords", "Keywords"),
]


def build(rows):
    """Собрать файл импорта. rows — список словарей с ключами из COLUMNS.

    Дополнительные поля карточки (`cf_*`) в COLUMNS не перечислены: их набор
    задаётся в админке сайта и у разных товаров разный. Поэтому колонки под них
    добавляются по факту — какие пришли в данных, такие и будут в файле.
    """
    extra = sorted({key for row in rows for key in row if key.startswith("cf_")})
    columns = COLUMNS + [(key, key) for key in extra]

    buffer = io.StringIO(newline="")
    writer = csv.writer(buffer, delimiter=";", quoting=csv.QUOTE_MINIMAL)
    writer.writerow([f"{field} : {title}" for field, title in columns])
    for row in rows:
        writer.writerow([row.get(field, "") for field, _ in columns])
    # errors="replace": в описаниях попадаются символы, которых нет в cp1251
    # (длинное тире, неразрывный пробел). Уронить выгрузку из-за них хуже,
    # чем потерять один знак.
    return buffer.getvalue().encode("cp1251", errors="replace")
