# api/services/section_snapshots.py
"""
Чтение и пересборка снимков разделов — общее для «Уценки» и обоих FBO.

Снимок собирают команды по расписанию, а страница читает базу. Здесь живут два
случая, когда читателю всё-таки приходится собирать самому: снимка ещё нет
(первый заход после выката) и человек нажал «Обновить».

**Замок.** Сборка идёт в МойСклад — от трёх до одиннадцати запросов. Без замка
любой F5 на пустом снимке порождает новую сборку, и при отказе по лимиту (429)
мы усиливаем ровно ту беду, ради которой снимки и заводились. Поэтому сборка
одна на раздел, а остальные ждущие получают либо прежний снимок, либо внятный
отказ.

**Остыть после падения.** Замок при неудаче не снимается, а дотлевает свой срок:
следующая попытка через минуту, а не на каждое обновление страницы. Это и есть
отрицательное кеширование — без него сломанный МойСклад означал бы шквал
запросов от каждого, кто открыл раздел.
"""
from django.core.cache import cache

from api.exceptions import ExternalServiceError
from api.models import SectionSnapshot

# Сборка самого тяжёлого раздела (уценка) занимает около трёх секунд; минута —
# с запасом на медленный ответ МойСклада и заодно пауза перед новой попыткой.
LOCK_TTL = 60


def _lock_key(key):
    return f'section_snapshot_build:{key}'


def _build_guarded(key, build):
    """Собрать раздел, если сборку никто не ведёт. Иначе — что есть или отказ."""
    if not cache.add(_lock_key(key), True, LOCK_TTL):
        stored = SectionSnapshot.stored(key)
        if stored:
            return stored.payload
        raise ExternalServiceError(
            'Данные раздела сейчас собираются. Обновите страницу через минуту.'
        )

    try:
        payload = build()
    except Exception:
        # Замок оставляем дотлевать: следующая попытка через минуту, а не сразу.
        raise

    cache.delete(_lock_key(key))
    return payload


def read(key, build):
    """Снимок из базы, а если его ещё ни разу не собирали — собрать один раз."""
    stored = SectionSnapshot.stored(key)
    if stored:
        return stored.payload
    return _build_guarded(key, build)


def rebuild(key, build):
    """Пересборка по явной просьбе — кнопкой «Обновить»."""
    return _build_guarded(key, build)


def drop(key):
    """Забыть снимок: следующий читатель соберёт заново.

    Нужно после действий, которые меняют то, что в снимке нарисовано, —
    снятия с продажи и публикации. Иначе колокольчик до получаса зовёт делать
    то, что человек уже сделал.
    """
    SectionSnapshot.objects.filter(key=key).delete()
