"""Справочник упаковочных коробок HorseBio.

Внутренние габариты (см) и лимит по весу берутся из реального списка тары
отдела упаковки. Размеры даны как (длина, ширина, высота) в сантиметрах —
для алгоритма раскладки важен только НАБОР трёх сторон, ориентация подбирается
при проверке влезаемости (см. packing.fits_by_dims).

Правило веса: коробку не набивают тяжелее MAX_BOX_WEIGHT_G (14 кг) — так пакует
отдел упаковки, независимо от того, сколько ещё влезло бы по объёму.
"""

from dataclasses import dataclass


# Отдел упаковки не делает коробки тяжелее 14 кг.
MAX_BOX_WEIGHT_G = 14_000

# Доля объёма коробки, которую реально удаётся заполнить товаром: остальное —
# «воздух», прокладки (картон, пупырка, стрейтч). Единственный калибровочный
# параметр модели: уточняется по 100 реальным упаковкам, пока разумный дефолт.
DEFAULT_FILL_RATE = 0.74


@dataclass(frozen=True)
class Box:
    """Тип коробки. dims_cm — три внутренних стороны (порядок не важен)."""
    code: str
    dims_cm: tuple[float, float, float]

    @property
    def volume_cm3(self) -> float:
        l, w, h = self.dims_cm
        return l * w * h

    @property
    def sorted_dims(self) -> tuple[float, float, float]:
        return tuple(sorted(self.dims_cm))  # type: ignore[return-value]


# Основной пул тары для автоподбора (внутренние ШГВ, см). Кубические/невысокие
# коробки под банки, флаконы, вёдра — то, из чего пакуется 99% заказов.
GENERAL_BOXES: tuple[Box, ...] = (
    Box("XS", (17, 12, 9)),
    Box("S", (20, 20, 13)),
    Box("M", (30, 25, 17)),
    Box("SM", (20, 20, 30)),
    Box("L", (31, 26, 38)),
    Box("XL", (40, 30, 40)),
)

# Спецтара — узкие длинные коробки под длинномер. НАМЕРЕННО вне автоподбора:
# по объёму они меньше XS, и алгоритм ошибочно тянул бы их под мелкие кубики
# (кубик влезает в сечение 6×6, но упаковщик так не пакует). Назначение «200»/
# «500» уточнить у отдела упаковки; включим адресно, если появятся длинномеры.
SPECIAL_BOXES: tuple[Box, ...] = (
    Box("200", (24, 6, 6)),
    Box("500", (30, 8, 8)),
)

BOXES: tuple[Box, ...] = GENERAL_BOXES + SPECIAL_BOXES

# Коробка, в которую по спецправилу пакуются вёдра 5,8 л (отдельно от прочего).
BUCKET_BOX_CODE = "M"

# Основной пул, отсортированный от меньшего объёма к большему — для подбора
# минимальной подходящей коробки под товар/остаток.
BOXES_BY_VOLUME: tuple[Box, ...] = tuple(sorted(GENERAL_BOXES, key=lambda b: b.volume_cm3))

BOX_BY_CODE: dict[str, Box] = {b.code: b for b in BOXES}
